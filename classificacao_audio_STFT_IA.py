# "entrada_teste", gurada os sinais de áudio usados no teste final depois que o teste termina..
# "rotulos_treino", guarda o rótulo correspondente, na mesma ordem...
# "rotulos_validacao", checam durante o treino...
# "rotulos_teste", medem o reultado final...
# "[1,2,3] , [4] , [5], isso dá uns 60% para treino, 20% para validação e 20% pra teste se forem do mesmo tamanho...
entrada_treino, rotulos_treino = ler_dataset(tabela_dados, [1, 2, 3])
entrada_validacao, rotulos_validacao = ler_dataset(tabela_dados, [4])
entrada_teste, rotulos_teste = ler_dataset(tabela_dados, [5])

