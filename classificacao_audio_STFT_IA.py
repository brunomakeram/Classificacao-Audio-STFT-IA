# "np.concatenate" junta todos os pedaços de áudio numa única sequência...
# Todos os espectrogramas devem usar o mesmo `fft_length`, `frame_step` e...
# `padding="same"` para produzir espectrogramas com formas idênticas...
# portanto, alinhando-os juntos. `expand_dims` garante que as formas sejam...
# compatível com modelos de imagem...

# 7 - Função que utilize o método STFTSpectrogrampara calcular três espectrogramas com múltiplas larguras de banda...
# Alinhá-los em uma imagem com diferentes canais para obter um espectrograma de múltiplas larguras de banda e, em seguida, plotar o espectrograma...


def desenhar_espectrograma_multibanda(dados_amostra_wav):

    espectrogramas = np.concatenate(
        [
            layers.STFTSpectrogram(
                mode="log",
                frame_length=TAXA_AMOSTRAGEM * x // 1000,
                frame_step=TAXA_AMOSTRAGEM * 5 // 1000,
                fft_length=1024,
                padding="same",
                expand_dims=True,
            )(dados_amostra_wav[None, ...])[0, ...]
            for x in [5, 10, 20]
        ],
        axis=-1,
    ).transpose([1, 0, 2])

    # Normalize cada canal de cor para uma melhor visualização...
    # "min" do numpy, devolve o menor valor...
    # "max" do numpy, devolve o maior valor...
    # "axis=(0)" calcula o minimo coluna por coluna, serve pro "max" também...
    # "axis=(1)" calcula o minimo linha por linha, serve pro "max" também...
    # "keepdims=True" numpy, mantém as dimensões originais do resultado...
    menor_valor = espectrogramas.min(axis=(0, 1), keepdims=True)
    maior_valor = espectrogramas.max(axis=(0, 1), keepdims=True)
    espectrogramas = (espectrogramas - menor_valor) / (maior_valor - menor_valor)

    plt.imshow(espectrogramas, origin="lower")
    plt.title("Espectrograma de múltiplas larguras de banda")
    plt.xlabel("Tempo")
    plt.ylabel("Frequência")


