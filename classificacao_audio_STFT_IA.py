# 5 - Defina funções para ler e pré-processar arquivos WAV...
# "taxa_original" taxa de amostragem original do arquivo WAV...
# "amostras_wav" array de amostras de áudio do arquivo WAV...
# "amostragem_alvo" taxa de amostragem alvo...
# "astype(np.float32)" converte o array de amostras de áudio para o tipo float32...
# "32768.0" normaliza as amostras de áudio para o intervalo [-1, 1]...
# "resample" altera a quantidade de amostras de um sinal...
def leitura_wav(path, amostragem_alvo=TAXA_AMOSTRAGEM):
    taxa_original, amostras_wav = scipy.io.wavfile.read(
        os.path.join(CAMINHO_DADOS, "audio", path)
    )
    amostras_wav = amostras_wav.astype(np.float32) / 32768.0
    numero_amostras = int(len(amostras_wav) * amostragem_alvo / taxa_original)
    amostras_wav = resample(amostras_wav, numero_amostras)
    # Adicionar uma dimensão de canal (de tamanho 1) para o array de áudio, para que ele tenha a forma (numero_amostras, 1) em vez de (numero_amostras)...
    return amostras_wav[:, None]


# 6- Função que utiliza o STFTSpectrogramespectrogram para calcular um espectrograma...
# "fft_length" tamanho da FFT (Fast Fourier Transform) usada para calcular o espectrograma...
# "frame_length" tamanho da janela de tempo usada para calcular o espectrograma...
# "trainable" indica se os parâmetros do espectrograma devem ser treináveis ou não...
# "dados_amostra_wav[None, ...]" adiciona uma dimensão extra ao array de amostras de áudio, para que ele tenha a forma (1, numero_amostras, 1) em vez de (numero_amostras, 1)...


def desenhar_espectrograma_wav(dados_amostra_wav):
    espectrograma = layers.STFTSpectrogram(
        mode="log",
        frame_length=TAXA_AMOSTRAGEM * 20 // 1000,
        frame_step=TAXA_AMOSTRAGEM * 5 // 1000,
        fft_length=1024,
        trainable=False,
    )(dados_amostra_wav[None, ...])[0, ...]

    # Desenhar o espectrograma usando a biblioteca matplotlib...
    # "plt.imshow" desenha uma imagem a partir de um array 2D...
    # "T" transposta do array, para que o eixo x seja o tempo e o eixo y seja a frequência...
    # "origin" define a origem da imagem, "lower" significa que a origem está no canto inferior esquerdo...
    # "title" define o título do gráfico...
    # "xlabel" define o rótulo do eixo x...
    # "ylabel" define o rótulo do eixo y...
    # "show" exibe o gráfico na tela...
    plt.imshow(espectrograma.T, origin="lower")
    plt.title("Espectrograma de canal único")
    plt.xlabel("Tempo")
    plt.ylabel("Frequência")


