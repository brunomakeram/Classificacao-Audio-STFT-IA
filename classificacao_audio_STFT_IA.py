# 9 - Define a função para ler o dataset...
# "tabela", DataFrame com os dados do dataset..
# "folds", quantas partes divide o dataset pra validação cruzada...
# "fold", coluna da tabela...
# "mascara", recebe o resultado de tabela["fold"]...
# "nomes_arquivos", guarda os nomes dos arquivos das amostras...
# "rotulos", guarda os rótulos das amostras do fold, na mesma ordem dos nomes dos arquivos...
# "sinais_wav", guarda os sinais de áudio dos arquivos do fold, lidos dos WAV e convertidos pra float32...
def ler_dataset(tabela, folds):
    mascara = tabela["fold"].isin(folds)
    nomes_arquivos = tabela["filename"][mascara]
    rotulos = tabela["target"][mascara].values
    sinais_wav = np.array(
        [leitura_wav(fil) for fil in nomes_arquivos], dtype=np.float32
    )
    # Devolve os sinais WAV e os rótulos...
    return sinais_wav, rotulos


